#!/usr/bin/env python3
"""
ips/eval/reproduce.py — Reproducible Results Compiler for docs/RESULTS.md (WP9, Rule B0 & H1).

Strictly reads ONLY from real evaluation outputs (`results/offline/`, `results/system/`,
`results/equivalence/`). Rejects any table whose `source` column contains `synthetic-smoke`.
If real data captures have not yet been executed on the Linux testbed, writes truthful
"NOT RUN (needs real data) — no real results yet" placeholders with git provenance.
"""
import os
import sys
import json
import subprocess
from datetime import datetime, timezone
import pandas as pd

REPO_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_MD = os.path.join(REPO_DIR, "docs", "RESULTS.md")


def _get_git_commit() -> str:
    try:
        out = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=REPO_DIR, stderr=subprocess.DEVNULL)
        return out.decode("utf-8").strip()
    except Exception:
        return "unknown"


def _load_real_csv(path: str) -> pd.DataFrame | None:
    if not os.path.exists(path):
        return None
    df = pd.read_csv(path)
    if len(df) == 0:
        return None
    # Rule B0: Strictly forbid synthetic-smoke data from entering docs/RESULTS.md
    if "source" in df.columns:
        sources = set(df["source"].astype(str).str.lower().tolist())
        if any("smoke" in s for s in sources):
            raise RuntimeError(f"CRITICAL B0 VIOLATION: {path} contains synthetic-smoke data!")
    return df


def generate_results_md(out_path: str = OUT_MD):
    commit = _get_git_commit()
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    offline_dir = os.path.join(REPO_DIR, "results", "offline")
    equiv_json = os.path.join(REPO_DIR, "results", "equivalence", "report.json")
    sys_csv = os.path.join(REPO_DIR, "results", "system", "system_eval.csv")
    drift_csv = os.path.join(REPO_DIR, "results", "offline", "drift_metrics.csv")

    models_df = _load_real_csv(os.path.join(offline_dir, "eval_models.csv"))
    lofo_df = _load_real_csv(os.path.join(offline_dir, "eval_families_lofo.csv"))
    quant_df = _load_real_csv(os.path.join(offline_dir, "quantization_table.csv"))
    prog_df = _load_real_csv(os.path.join(offline_dir, "progressive_pareto.csv"))
    cross_df = _load_real_csv(os.path.join(offline_dir, "cross_domain_iot23.csv"))
    evas_df = _load_real_csv(os.path.join(offline_dir, "evasion_cost_curve.csv"))
    calib_df = _load_real_csv(os.path.join(offline_dir, "calibration_curve.csv"))
    imp_df = _load_real_csv(os.path.join(offline_dir, "netem_impairment.csv"))
    contam_df = _load_real_csv(os.path.join(offline_dir, "contamination_study.csv"))
    cesnet_df = _load_real_csv(os.path.join(offline_dir, "cesnet_natural_drift.csv"))
    sys_df = _load_real_csv(sys_csv)
    drift_df = _load_real_csv(drift_csv)

    lines = [
        "# Experimental Results (`docs/RESULTS.md`)",
        "",
        "> **Provenance**: Auto-generated by `ips/eval/reproduce.py` (`make reproduce`).",
        f"> **Git Commit**: `{commit}` | **Generated At**: `{ts}` | **Config**: `configs/system.yaml`",
        "> **Honesty Rule B0**: `results/smoke/` (`source=\"synthetic-smoke\"`) is strictly excluded from this file.",
        "",
        "## 1. Offline Zero-Day Detection & Model Comparison (WP5)",
        "",
    ]

    if models_df is not None:
        lines.append(models_df.to_markdown(index=False))
    else:
        lines.append("**Status**: `NOT RUN (needs real data) — no real results yet`")
        lines.append("")
        lines.append("Run Step 3 of `docs/USER_TEST_GUIDE.md` on the Linux VM to populate `results/offline/eval_models.csv`.")

    lines.extend([
        "",
        "## 2. Leave-One-Attack-Family-Out (LOFO) Zero-Day Protocol (WP5, B1)",
        "",
    ])
    if lofo_df is not None:
        lines.append(lofo_df.to_markdown(index=False))
    else:
        lines.append("**Status**: `NOT RUN (needs real data) — no real results yet`")

    lines.extend([
        "",
        "## 3. ONNX INT8 Quantization & Latency Microbenchmark (WP5, N5)",
        "",
    ])
    if quant_df is not None:
        lines.append(quant_df.to_markdown(index=False))
    else:
        lines.append("**Status**: `NOT RUN (needs real data) — no real results yet`")

    lines.extend([
        "",
        "## 4. Kernel-vs-Offline Feature Equivalence (WP6, N6)",
        "",
    ])
    if os.path.exists(equiv_json):
        with open(equiv_json, "r", encoding="utf-8") as f:
            eq = json.load(f)
        lines.append(f"- **Matched Flows**: {eq.get('matched_flows', 0)}")
        lines.append(f"- **`sizes[0..N-1]` Exact Match**: {eq.get('size_exact_match_rate', 0.0)*100:.2f}%")
        lines.append(f"- **`dirs[0..N-1]` Exact Match**: {eq.get('dir_exact_match_rate', 0.0)*100:.2f}%")
        lines.append(f"- **`|IAT_kernel - IAT_pcap|` p50 / p95 / p99**: {eq.get('iat_diff_p50_us', 0.0):.2f} / {eq.get('iat_diff_p95_us', 0.0):.2f} / {eq.get('iat_diff_p99_us', 0.0):.2f} us")
    else:
        lines.append("**Status**: `NOT RUN (Linux required) — run sudo bash scripts/equivalence_test.sh`")

    lines.extend([
        "",
        "## 5. Inline Enforcement, Attack-Packet Leakage & Fast-Path Bypass (WP7, N2)",
        "",
    ])
    if sys_df is not None:
        lines.append(sys_df.to_markdown(index=False))
    else:
        lines.append("**Status**: `NOT RUN (Linux + real data required) — no real results yet`")

    lines.extend([
        "",
        "## 6. Concept Drift & Poisoning-Aware Drift Guard S1–S5 (WP8, N1 + N4)",
        "",
    ])
    if drift_df is not None:
        lines.append(drift_df.to_markdown(index=False))
    else:
        lines.append("**Status**: `NOT RUN (needs real data) — no real results yet`")

    for sec_num, sec_title, sec_df, extra_note in [
        (7, "Progressive Multi-Checkpoint Inference (`[4, 8, 16]`, C1 / N7)", prog_df, None),
        (8, "Cross-Domain Benign Generalisation (`Testbed <-> IoT-23`, B6)", cross_df, None),
        (9, "White-Box Adaptive-Attacker Cost-of-Evasion Curve (`Q=200`, C3 / N8)", evas_df, None),
        (10, "Split-Conformal vs EVT Tail Threshold Calibration (C9 / N9)", calib_df, None),
        (11, "Network-Impairment Robustness & Feature Ablation (C11 / N11)", imp_df, None),
        (12, "Training-Set Contamination & Trimmed-Loss Mitigation (C12 / N12)", contam_df, None),
        (
            13,
            "CESNET-TLS-Year22 Multi-Week Natural Benign Drift (B5)",
            cesnet_df,
            "> **Note (B5)**: CESNET has hashed IPs and no device identities; only G1, G3, G4, and EVT recalibration apply here — G2 (cross-device quorum) is never claimed from CESNET.",
        ),
    ]:
        lines.extend(["", f"## {sec_num}. {sec_title}", ""])
        if extra_note:
            lines.extend([extra_note, ""])
        if sec_df is not None:
            lines.append(sec_df.to_markdown(index=False))
        else:
            lines.append("**Status**: `NOT RUN (needs real data) — no real results yet`")

    lines.append("")
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"[+] Wrote {out_path}")


if __name__ == "__main__":
    generate_results_md()

